#!/usr/bin/env python3
"""Check tutorials 9–15. Source checks are the default; rendering is explicitly requested.

--runtime executes the existing Racket figure-helper tests and Scribble smoke page.
--render also compiles and renders all seven manuals using their real evaluators.
--html-root inspects an existing seven-directory render. None of these checks opens
GUI windows, exercises a GPU, or certifies installed/hosted documentation links.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
SLUGS = ('pdf-svg', 'effects', 'pictures', 'vector-raster', 'gpu', 'animation', 'interaction')
COUNTS = dict(zip(SLUGS, (5, 8, 8, 8, 2, 3, 5)))

# Reuse the source reader and HTML resource checks added with the first eight lessons.
_spec = importlib.util.spec_from_file_location('tutorial_check_3c',
                                              Path(__file__).with_name('check-3c.py'))
assert _spec is not None and _spec.loader is not None
figures = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(figures)
need = figures.need


def manual_path(root: Path, slug: str) -> Path:
    return root / 'scribblings' / 'tutorials' / slug / (slug + '.scrbl')


def section(text: str, heading: str) -> str:
    """Return a named section, excluding the next section's heading."""
    pattern = r'@section(?:\[[^\]]*\])?\{' + re.escape(heading) + r'\}'
    match = re.search(pattern, text)
    need(match is not None, f'missing section: {heading}')
    end = text.find('@section', match.end())
    return text[match.end():end if end >= 0 else len(text)]


def check_source(root: Path) -> dict:
    rows = {}
    sources = {}
    for slug in SLUGS:
        text = manual_path(root, slug).read_text(encoding='utf-8')
        sources[slug] = text
        alternatives = figures.source_alternatives(text)
        need(len(alternatives) == COUNTS[slug], f'{slug}: missing or extra described figure')
        need('"../support/accessible-figures.rkt"' in text, f'{slug}: missing figure import')
        need(text.index('@(tutorial-figure') < text.index(f'@tutorial-entry["{slug}"]'),
             f'{slug}: setup precedes the finished result')
        for helper in ('tutorial-entry', 'tutorial-next', 'tutorial-sources'):
            need(text.count(f'@{helper}["{slug}"]') == 1, f'{slug}: lost reader navigation')
        for tag in ('finished-result', 'try-it', 'next-steps', 'example-source'):
            need(text.count(f'#:tag "{tag}"') == 1, f'{slug}: missing or duplicate {tag}')
        need(not re.search(r'@\w+-image\[|@\((?:[\w-]*pict|animation-frame-strip)\b', text),
             f'{slug}: figure bypasses descriptive markup')
        need(not re.search(r'documentation build|separately (?:designed|prepared|maintained)|'
                           r'generated by calling|not a second version redrawn', text),
             f'{slug}: production commentary remains')
        need(not re.search(r'Tutorial \d+|@tt\{[^}]*--', text),
             f'{slug}: numbered prerequisite or nonliteral command option')
        rows[slug] = dict(described_figures=len(alternatives), alternatives=alternatives)

    recording = section(sources['pictures'], 'A Picture Is Not an Image')
    need('record image' in recording
         and 'does not turn those pixels into vector geometry' in recording,
         'recording still implies vector-only content')
    need('@tutorial-link["vector-raster"]' in recording, 'missing output-representation link')
    need('returns a @racket[picture?]' not in sources['pictures'], 'picture predicate used as value')
    need('recognized by\n@racket[gpu-context?]' in sources['gpu'], 'GPU predicate not explained')
    exercise = section(sources['gpu'], 'Try It')
    for name in ('metal-image', 'windows-image', 'linux-image'):
        need(f'@racket[{name}]' in exercise, f'missing {name} exercise route')
    need('while\n@racket[linux-image] is in scope' in exercise, 'Linux save escapes local scope')
    need('(save-image linux-image "scene-opengl-again.png"' in exercise,
         'missing concrete repeated-save example')
    need('no further readback' in exercise, 'missing CPU-owned-image lesson')

    animation = sources['animation']
    opening = section(animation, 'The Finished Animation')
    for mode in ('raster', 'gpu'):
        need(f'  --renderer {mode}' in opening, f'{mode} run command not near opening')
    need(animation.count('If GPU mode is unavailable') == 1, 'missing/duplicated GPU recovery')
    need('silently retrying on the CPU' in opening, 'missing explicit-failure rule')
    need('A reliable automatic fallback' not in animation, 'unimplemented recovery design remains')
    need('GPU mode selects Metal' not in animation, 'duplicate platform summary remains')
    need('(define (preferred-gpu-backend)' in animation, 'backend selection code was removed')
    need('GPU canvas is borrowed and expires' in animation, 'missing borrowed-frame lifetime')
    need('stop the timer before retiring' in animation, 'missing close-order rule')
    need('(gpu-frame-scale-x frame)' in sources['interaction'], 'editor backing scale lost')
    need('a label is hidden' in sources['interaction'], 'missing small-client exercise boundary')
    need('18-unit hit radius' in sources['interaction'], 'hit-test size distinction lost')
    return rows


class Page(figures.Page):
    def __init__(self) -> None:
        super().__init__()
        self.unlabelled = []
        self.image_sizes = []

    def handle_starttag(self, tag: str, attrs: list) -> None:
        super().handle_starttag(tag, attrs)
        values = dict(attrs)
        classes = set(values.get('class', '').split())
        if tag == 'img':
            if figures.MARKER in classes:
                self.image_sizes.append((values.get('width'), values.get('height')))
            elif (values.get('alt', '').lower() in ('image', 'picture')
                  or re.search(r'(?:^|/)pict(?:_\d+)?\.png$', values.get('src', ''))):
                self.unlabelled.append(values)


def inspect_html(path: Path, expected: list[str], *, strict_links: bool = False) -> dict:
    result = figures.inspect_html(path, expected)
    page = Page()
    page.feed(path.read_text(encoding='utf-8'))
    need(not page.unlabelled, f'{path}: unwrapped generic figure')
    for size in page.image_sizes:
        try:
            valid = all(0 < float(value) < float('inf') for value in size)
        except (TypeError, ValueError):
            valid = False
        need(valid, f'{path}: missing or invalid displayed figure dimensions')
    if strict_links:
        need(result['unresolved_references'] == 0, f'{path}: unresolved references')
        need(result['machine_local_links'] == 0, f'{path}: machine-local links')
    result['strict_links'] = strict_links
    return result


def inspect_tree(root: Path, html: Path, *, strict_links: bool = False) -> dict:
    return {
        slug: inspect_html(html / slug / (slug + '.html'),
                           figures.source_alternatives(manual_path(root, slug).read_text()),
                           strict_links=strict_links)
        for slug in SLUGS
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--runtime', action='store_true')
    parser.add_argument('--render', action='store_true', help='implies --runtime; needs native Skia')
    parser.add_argument('--racket', default='racket')
    parser.add_argument('--html-root', type=Path)
    parser.add_argument('--strict-links', action='store_true', help='reject badlink and file: links')
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    root = args.root.resolve()
    if args.output is None:
        (root / 'output').mkdir(exist_ok=True)
        output = Path(tempfile.mkdtemp(prefix='tutorials-3d-', dir=root / 'output'))
    else:
        output = args.output.resolve()
        need(not output.exists() or not any(output.iterdir()),
             'use a fresh output directory; do not mix evidence from different runs')
        output.mkdir(parents=True, exist_ok=True)
    report = dict(status='failed', commands=[], runtime='not executed',
                  full_manuals='not executed', installed_documentation='not executed',
                  native_examples='not executed separately', gui_gpu='not executed')

    def run(name: str, command: list[str], timeout: int = 180) -> None:
        record = dict(name=name, command=command, status='running')
        report['commands'].append(record)
        log = output / (name + '.log')
        try:
            result = subprocess.run(command, cwd=root, capture_output=True, text=True,
                                    encoding='utf-8', errors='replace', timeout=timeout)
            log.write_text(result.stdout + result.stderr, encoding='utf-8')
            record['returncode'] = result.returncode
            need(result.returncode == 0, f'{name} failed; see {log}')
            record['status'] = 'passed'
        except Exception as error:
            record['status'] = 'failed'
            record['error'] = str(error)
            if not log.exists():
                log.write_text(str(error) + '\n', encoding='utf-8')
            raise

    try:
        report['source'] = check_source(root)
        if args.html_root:
            report['supplied_html'] = inspect_tree(root, args.html_root,
                                                   strict_links=args.strict_links)
        if args.runtime or args.render:
            racket = shutil.which(args.racket)
            need(racket is not None, f'Racket executable not found: {args.racket}')
            raco = [racket, '-l', 'raco', '--']
            support = root / 'scribblings/tutorials/support'
            run('helper-tests', [*raco, 'test', str(support / 'accessible-figures-test.rkt')])
            smoke = output / 'smoke'
            smoke.mkdir()
            run('smoke-render', [*raco, 'scribble', '--html', '--dest', str(smoke),
                                 str(support / 'early-figures-smoke.scrbl')])
            report['runtime'] = figures.check_smoke(smoke / 'early-figures-smoke.html')
            if args.render:
                report['full_manuals'] = {}
                for slug in SLUGS:
                    source = manual_path(root, slug)
                    run(slug + '-compile', [*raco, 'make', str(source)])
                    destination = output / slug
                    destination.mkdir()
                    run(slug + '-render', [*raco, 'scribble', '--html', '--dest', str(destination),
                                          '--redirect-main', 'https://docs.racket-lang.org/',
                                          str(source)], timeout=300)
                    alternatives = figures.source_alternatives(source.read_text(encoding='utf-8'))
                    report['full_manuals'][slug] = inspect_html(
                        destination / (slug + '.html'), alternatives,
                        strict_links=args.strict_links)
        report['status'] = 'passed'
    except Exception as error:
        report['error'] = str(error)
    (output / 'validation.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(report, indent=2))
    print(f'Validation record: {output}')
    return 0 if report['status'] == 'passed' else 1


if __name__ == '__main__':
    raise SystemExit(main())
