#!/usr/bin/env python3
"""Check the first eight tutorial revisions; opt in to Racket and actual Scribble rendering.

The default is source inspection only. --runtime runs the Racket helper tests and
renders a Skia-free Scribble smoke page. --render also compiles and renders all
eight Skia manuals. These are not installed-documentation, GUI, or GPU acceptance.
"""
from __future__ import annotations

import argparse
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import shutil
import struct
import subprocess
import tempfile
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[2]
SLUGS = ('quick', 'clock', 'logo', 'images', 'poster', 'text', 'shaping', 'paragraph')
COUNTS = dict(zip(SLUGS, (9, 13, 10, 6, 12, 6, 6, 7)))
FINISHED = dict(zip(SLUGS, (9, 10, 10, 6, 12, 6, 6, 7)))
MARKER = 'skia-tutorial-figure'


def need(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def manual_path(root: Path, slug: str) -> Path:
    directory = root / 'scribblings'
    if slug != 'quick':
        directory /= 'tutorials'
    return directory / slug / f'{slug}.scrbl'


def form_end(text: str, start: int) -> int:
    """Bounded delimiter scan for the Racket expressions used in these figure calls.

    This is a source inspector, not a replacement for Racket's reader or expander.
    """
    stack = []
    i = start
    while i < len(text):
        char = text[i]
        if char == '"':
            i += 1
            while i < len(text):
                if text[i] == '\\':
                    i += 2
                    continue
                if text[i] == '"':
                    break
                i += 1
        elif char == ';':
            i = text.find('\n', i)
            need(i >= 0, 'unterminated source comment')
        elif text.startswith('#\\', i):
            i += 3
            while i < len(text) and (text[i].isalnum() or text[i] == '-'):
                i += 1
            continue
        elif char in '([{':
            stack.append(char)
        elif char in ')]}':
            need(bool(stack) and '([{'.index(stack[-1]) == ')]}'.index(char),
                 f'mismatched source delimiter at {i}')
            stack.pop()
            if not stack:
                return i + 1
        i += 1
    raise ValueError(f'missing closing source delimiter after {start}')


def source_alternatives(text: str) -> list[str]:
    descriptions = []
    for match in re.finditer(r'\(tutorial-figure\s+', text):
        start = match.end()
        if text[start] == '"':
            token = re.match(r'"(?:[^"\\]|\\.)*"', text[start:])
            need(token is not None, 'unfinished alternative string')
            description = json.loads(token[0])
        else:
            need(text.startswith('(string-append', start), 'nonliteral figure alternative')
            end = form_end(text, start)
            strings = re.findall(r'"(?:[^"\\]|\\.)*"', text[start:end])
            description = ''.join(json.loads(token) for token in strings)
        need(len(description.split()) >= 4, f'uninformative alternative: {description!r}')
        descriptions.append(description)
    return descriptions


def check_source(root: Path) -> dict:
    rows = {}
    for slug in SLUGS:
        text = manual_path(root, slug).read_text(encoding='utf-8')
        descriptions = source_alternatives(text)
        need(len(descriptions) == COUNTS[slug], f'{slug}: lost or extra figure')
        need(text.count('(make-figure-preview)') == 1, f'{slug}: missing preview slot')
        need(text.count('(finish-figure\n') == 1, f'{slug}: missing final-figure assignment')
        need(text.count('@|finished-preview|') == 1, f'{slug}: missing opening placement')
        need('#:tag "finished-result"' in text, f'{slug}: missing opening section tag')
        need(text.index('@|finished-preview|') < text.index(f'@tutorial-entry["{slug}"]'),
             f'{slug}: setup obscures the finished result')
        need(not re.search(r'@\w+-image\[|@\(paragraph-article-pict\)', text),
             f'{slug}: figure bypasses descriptive markup')
        need(not re.search(r'documentation (?:is built|build)|not a separately|generated by calling',
                           text), f'{slug}: remaining production commentary')
        for helper in ('tutorial-entry', 'tutorial-next', 'tutorial-sources'):
            need(text.count(f'@{helper}["{slug}"]') == 1, f'{slug}: lost 3B reader helper')
        for tag in ('finished-result', 'try-it', 'next-steps', 'example-source'):
            need(text.count(f'#:tag "{tag}"') == 1, f'{slug}: duplicate/missing {tag}')
        rows[slug] = dict(described_figures=len(descriptions),
                          expected_rendered_placements=len(descriptions) + 1)
    quick = manual_path(root, 'quick').read_text(encoding='utf-8')
    for heading in ('Ready: Load Skia', 'Set: Choose a Surface Size',
                    'Go: Draw and Save a Rectangle'):
        need(f'@section{{{heading}}}' in quick, f'missing setup heading: {heading}')
    clock = manual_path(root, 'clock').read_text(encoding='utf-8')
    need('The hands move continuously' not in clock, 'static clock still described as animated')
    for caption in ('Translate, then rotate', 'Rotate, then translate'):
        need(f'@centered{{@bold{{{caption}}}}}' in clock, f'missing caption: {caption}')
    logo = manual_path(root, 'logo').read_text(encoding='utf-8')
    need('@section{Cut a Hole with a Second Contour}' in logo, 'contour step was not merged')
    text = manual_path(root, 'text').read_text(encoding='utf-8')
    need('simple Latin' in text[:text.index('@tutorial-entry')], 'late simple-text boundary')
    shaping = manual_path(root, 'shaping').read_text(encoding='utf-8')
    need('returns a @racket[shaped-run?]' not in shaping, 'predicate still used as a value name')
    need('without clipping' not in shaping, 'advance alignment still promises ink clipping')
    need('advance alignment, not ink alignment' in shaping, 'missing advance/ink distinction')
    paragraph = manual_path(root, 'paragraph').read_text(encoding='utf-8')
    need('The two drawing APIs use different origins' in paragraph, 'missing origin distinction')
    for call in ('(draw-text-layout canvas introduction 88 222 ink)',
                 '(draw-mixed-text-layout canvas multilingual-text 88 376 ink)',
                 '(draw-mixed-text-layout canvas right-to-left-text 108 562 ink)'):
        need(call in paragraph, f'missing article assembly excerpt: {call}')
    return rows


class Page(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.figures = []
        self.position = 0
        self.first_code = None
        self.badlinks = self.rkt_errors = self.file_links = 0

    def handle_starttag(self, tag: str, attrs: list) -> None:
        self.position += 1
        values = dict(attrs)
        classes = set(values.get('class', '').split())
        self.badlinks += int('badlink' in classes)
        self.rkt_errors += int('RktErr' in classes)
        self.file_links += int(values.get('href', '').startswith('file:'))
        if self.first_code is None and 'RktBlk' in classes:
            self.first_code = self.position
        if tag == 'img' and MARKER in classes:
            self.figures.append(dict(values, position=self.position))

    def handle_startendtag(self, tag: str, attrs: list) -> None:
        self.handle_starttag(tag, attrs)


def inspect_html(path: Path, expected: list[str]) -> dict:
    page = Page()
    page.feed(path.read_text(encoding='utf-8'))
    need([figure.get('alt') for figure in page.figures] == expected,
         f'{path}: missing, generic, or reordered figure alternatives')
    need(bool(page.figures), f'{path}: no described figures')
    if page.first_code is not None:
        need(page.figures[0]['position'] < page.first_code, f'{path}: code precedes opening figure')
    for figure in page.figures:
        url = urlsplit(figure.get('src', ''))
        need(bool(url.path) and not url.scheme and not url.netloc, 'non-local figure resource')
        resource = path.parent / unquote(url.path)
        need(resource.is_file(), f'missing figure resource: {resource}')
        with resource.open('rb') as stream:
            header = stream.read(24)
        need(len(header) == 24 and header[:8] == b'\x89PNG\r\n\x1a\n'
             and header[12:16] == b'IHDR', f'invalid PNG header: {resource}')
        need(all(size > 0 for size in struct.unpack('>II', header[16:24])),
             f'zero-size figure: {resource}')
    need(page.rkt_errors == 0, f'{path}: Racket evaluation-error elements')
    return dict(figures=len(page.figures), unresolved_references=page.badlinks,
                racket_error_elements=page.rkt_errors, machine_local_links=page.file_links)


def check_smoke(path: Path) -> dict:
    final = 'Finished panel: Bézier -- origin & scale.'
    expected = [final, 'Direct panel: 24 by 16.', final]
    result = inspect_html(path, expected)
    page = Page()
    page.feed(path.read_text(encoding='utf-8'))
    need(page.figures[0]['src'] == page.figures[2]['src'], 'preview did not reuse final resource')
    for figure, size in zip(page.figures, ((32, 20), (24, 16), (32, 20))):
        actual = tuple(float(figure.get(dimension, 'nan')) for dimension in ('width', 'height'))
        need(actual == size, f'high-density figure changed displayed dimensions: {actual}')
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--runtime', action='store_true')
    parser.add_argument('--render', action='store_true', help='implies --runtime; needs native Skia')
    parser.add_argument('--racket', default='racket')
    parser.add_argument('--smoke-html', type=Path)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    root = args.root.resolve()
    output = args.output
    if output is None:
        (root / 'output').mkdir(exist_ok=True)
        output = Path(tempfile.mkdtemp(prefix='tutorials-3c-', dir=root / 'output'))
    output = output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    report = dict(status='failed', commands=[],
                  runtime=('requested; not executed'
                           if args.runtime or args.render else 'not requested'),
                  full_manuals='requested; not executed' if args.render else 'not requested',
                  installed_documentation='not executed',
                  gui_gpu='not executed')

    def run(name: str, command: list[str], timeout: int = 180) -> None:
        record = dict(name=name, command=command, status='running')
        report['commands'].append(record)
        try:
            result = subprocess.run(command, cwd=root, capture_output=True, text=True,
                                    encoding='utf-8', errors='replace', timeout=timeout)
            (output / f'{name}.log').write_text(result.stdout + result.stderr, encoding='utf-8')
            record['returncode'] = result.returncode
            need(result.returncode == 0, f'{name} failed; see {output / (name + ".log")}')
            record['status'] = 'passed'
        except Exception:
            record['status'] = 'failed'
            raise

    try:
        report['source'] = check_source(root)
        if args.smoke_html:
            report['supplied_smoke_html'] = check_smoke(args.smoke_html)
        if args.runtime or args.render:
            racket = shutil.which(args.racket)
            need(racket is not None, f'Racket executable not found: {args.racket}')
            raco = [racket, '-l', 'raco', '--']
            support = root / 'scribblings/tutorials/support'
            run('helper-tests', [*raco, 'test', str(support / 'accessible-figures-test.rkt')])
            smoke = output / 'smoke'
            smoke.mkdir(exist_ok=True)
            run('smoke-render', [*raco, 'scribble', '--html', '--dest', str(smoke),
                                 str(support / 'early-figures-smoke.scrbl')])
            report['runtime'] = check_smoke(smoke / 'early-figures-smoke.html')
            if args.render:
                report['full_manuals'] = {}
                for slug in SLUGS:
                    source = manual_path(root, slug)
                    run(slug + '-compile', [*raco, 'make', str(source)])
                    destination = output / slug
                    destination.mkdir(exist_ok=True)
                    run(slug + '-render', [*raco, 'scribble', '--html', '--dest', str(destination),
                                          '--redirect-main', 'https://docs.racket-lang.org/',
                                          str(source)], timeout=300)
                    alternatives = source_alternatives(source.read_text(encoding='utf-8'))
                    expected = [alternatives[FINISHED[slug] - 1], *alternatives]
                    report['full_manuals'][slug] = inspect_html(
                        destination / f'{slug}.html', expected)
        report['status'] = 'passed'
    except Exception as error:
        report['error'] = str(error)
    (output / 'validation.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(report, indent=2))
    print(f'Validation record: {output}')
    return 0 if report['status'] == 'passed' else 1


if __name__ == '__main__':
    raise SystemExit(main())
