#include <windows.h>
#include <dxgi1_4.h>
#include <d3d12.h>
#include <cstring>
extern "C" int check_d3d12_guids(void) {
    const unsigned char factory[16] = {0x02,0xea,0xc6,0x1b,0x36,0xef,0x4f,0x46,0xbf,0x0c,0x21,0xca,0x39,0xe5,0x16,0x8a};
    const unsigned char adapter[16] = {0x61,0x8f,0x03,0x29,0x39,0x38,0x26,0x46,0x91,0xfd,0x08,0x68,0x79,0x01,0x1a,0x05};
    const unsigned char device[16] = {0xf1,0x19,0x98,0x18,0xb6,0x1d,0x57,0x4b,0xbe,0x54,0x18,0x21,0x33,0x9b,0x85,0xf7};
    const unsigned char queue[16] = {0xa6,0x70,0xc8,0x0e,0x7e,0x5d,0x22,0x4c,0x8c,0xfc,0x5b,0xaa,0xe0,0x76,0x16,0xed};
    return std::memcmp(factory, &__uuidof(IDXGIFactory4),16)==0 &&
           std::memcmp(adapter, &__uuidof(IDXGIAdapter1),16)==0 &&
           std::memcmp(device, &__uuidof(ID3D12Device),16)==0 &&
           std::memcmp(queue, &__uuidof(ID3D12CommandQueue),16)==0;
}
